#!/usr/bin/env node
// Generates masterplan/reference/state-keys.md from src/state/registry.ts's
// KEY_REGISTRY — the single source of truth (Feature 05.9.3). Run manually,
// committed output, no Actions.
//
// Usage:
//   node scripts/gen-state-keys.mjs [--check]
//
// --check   regenerate to memory, diff against the committed doc, exit
//           nonzero on drift (Feature 05.9.4) — wire this into the standing
//           verification checklist alongside lint/typecheck/test.
//
// Parses registry.ts and the state modules as *source text* rather
// than executing them: their imports resolve `setValue` etc. from the bare
// 'spektrum' specifier, which only exists via a browser import map or the
// Vitest alias — not in plain Node. Same source-text-parsing convention as
// scripts/check-css.mjs and scripts/check-importmap.mjs elsewhere in this
// repo, applied to TypeScript instead of CSS/HTML.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const stateDir = `${repoRoot}src/state`;
const outPath = `${repoRoot}masterplan/reference/state-keys.md`;
const checkOnly = process.argv.includes('--check');

const MODULE_FILES = ['playlist.ts', 'import.ts', 'player.ts', 'epg.ts', 'settings.ts', 'ui.ts', 'list.ts', 'list-state.ts', 'list-groups.ts', 'live.ts', 'favorites.ts'];

/** Every top-level `export const NAME = <value>;` across the five module files — key-string constants and the odd numeric one (e.g. ZAP_HISTORY_CAP) that registry.ts references for `maxItems`. */
function collectConstants() {
    const consts = new Map();
    const pattern = /export const ([A-Z][A-Z0-9_]*)\s*=\s*(?:'([^']*)'|(\d[\d_]*))/g;
    for (const file of MODULE_FILES) {
        const src = readFileSync(`${stateDir}/${file}`, 'utf8');
        for (const [, name, quoted, numeric] of src.matchAll(pattern)) {
            consts.set(name, quoted !== undefined ? quoted : numeric.replace(/_/g, ''));
        }
    }
    return consts;
}

function resolveExpr(expr, consts) {
    const trimmed = expr.trim();
    if (/^\d+$/.test(trimmed)) return trimmed;
    if (consts.has(trimmed)) return consts.get(trimmed);
    throw new Error(`gen-state-keys: could not resolve "${trimmed}" against any known state constant.`);
}

function parseRegistry(consts) {
    const src = readFileSync(`${stateDir}/registry.ts`, 'utf8');
    const bodyMatch = /export const KEY_REGISTRY[^{]*=\s*{([\s\S]*?)\n};/.exec(src);
    if (!bodyMatch) throw new Error('gen-state-keys: could not find the KEY_REGISTRY object literal in registry.ts — has its shape changed?');

    const entryPattern = /\[([A-Z][A-Z0-9_]*)\]:\s*{([\s\S]*?)\n\s{4}},/g;
    const entries = [];
    for (const [, keyConst, fields] of bodyMatch[1].matchAll(entryPattern)) {
        const key = consts.get(keyConst);
        if (!key) throw new Error(`gen-state-keys: unresolved key constant "${keyConst}" — is it exported from one of ${MODULE_FILES.join(', ')}?`);

        const owner = /owner:\s*'([a-z]+)'/.exec(fields)?.[1];
        const description = /description:\s*'((?:[^'\\]|\\.)*)'/.exec(fields)?.[1];
        if (!owner || description === undefined) {
            throw new Error(`gen-state-keys: could not parse owner/description for "${keyConst}" — the entry's shape drifted from what this script expects.`);
        }

        const maxItemsExpr = /maxItems:\s*([^\s,]+),/.exec(fields)?.[1];
        entries.push({
            key,
            owner,
            persisted: /persisted:\s*true/.test(fields),
            maxItems: maxItemsExpr ? resolveExpr(maxItemsExpr, consts) : null,
            version: /version:\s*(\d+)/.exec(fields)?.[1] ?? '1',
            description,
        });
    }

    if (entries.length === 0) {
        throw new Error("gen-state-keys: parsed zero KEY_REGISTRY entries — the regex has drifted from registry.ts's actual shape.");
    }
    return entries.sort((a, b) => a.key.localeCompare(b.key));
}

function renderDoc(entries) {
    const rows = entries
        .map(
            (e) =>
                `| \`${e.key}\` | ${e.owner} | ${e.persisted ? 'yes' : 'no'} | ${e.maxItems ?? '—'} | v${e.version} | ${e.description} |`,
        )
        .join('\n');

    const bootCritical = entries.filter((e) => e.persisted && (e.key.startsWith('player.') || e.key === 'settings.proxyTemplate'));

    return `# State keys reference

Generated by \`scripts/gen-state-keys.mjs\` from \`src/state/registry.ts\`'s
\`KEY_REGISTRY\` — do not hand-edit; regenerate after any registry change
(\`node scripts/gen-state-keys.mjs\`) and commit the diff. \`--check\` verifies
this file hasn't drifted from the registry (wired into the standing
verification checklist, Feature 05.9.4).

Each owning module's own \`*State\` interface (\`playlist.ts\`'s \`PlaylistState\`,
\`player.ts\`'s \`PlayerState\`, etc.) is the per-key TypeScript type — not
repeated here, to avoid the two drifting apart.

| Key | Owner | Persisted | Max items | Envelope version | Description |
| --- | --- | --- | --- | --- | --- |
${rows}

## Session-restore boot-critical set (Feature 05.9.5)

These persisted keys are what \`rehydrateState()\` restores *before* any
heavy playlist load (masterplan §6.4) — the pair that makes reboot feel
instant:

${bootCritical.map((e) => `- \`${e.key}\` (v${e.version}${e.maxItems ? `, capped at ${e.maxItems}` : ''})`).join('\n')}

\`settings.proxyTemplate\` is also boot-critical in the sense that it must be
restored before any proxied network request, even though it isn't part of
the player-restore pair above.

## Sanctioned non-action publishers (Feature 05.9.6)

Two keys are written directly with \`setValue\`, not through a \`defineFn\`
action — see \`src/state/README.md\`'s "Sanctioned non-action publishers"
section for the full rationale:

- \`ui.activeView\` — \`src/app/router.ts\`'s \`applyRoute()\`.
- \`epg.tick\` — \`src/state/epg.ts\`'s \`startEpgTick()\`.

## Naming rules (Feature 05.9.7)

- Keys: \`module.camelCase\`.
- Actions: \`module/verbPhrase\` (the \`defineFn\` name is also the \`data-fn\`
  markup attribute).
- Renaming a persisted key requires a Feature 04.9 migration hook and a
  \`KeyMeta.version\` bump in the same commit.
`;
}

const consts = collectConstants();
const entries = parseRegistry(consts);
const rendered = renderDoc(entries);

if (checkOnly) {
    let committed;
    try {
        committed = readFileSync(outPath, 'utf8');
    } catch {
        console.error(`gen-state-keys: --check failed — ${outPath} does not exist. Run \`node scripts/gen-state-keys.mjs\` first.`);
        process.exit(1);
    }
    if (committed !== rendered) {
        console.error(`gen-state-keys: --check failed — ${outPath} is out of date with src/state/registry.ts. Regenerate with \`node scripts/gen-state-keys.mjs\`.`);
        process.exit(1);
    }
    console.log(`gen-state-keys: OK — ${outPath} matches src/state/registry.ts (${entries.length} keys)`);
} else {
    writeFileSync(outPath, rendered);
    console.log(`gen-state-keys: wrote ${outPath} (${entries.length} keys)`);
}
